// 平滑的有機外形（水池、沙坑）
function blob(cx, cy, rx, ry, seed = 1, wob = 0.12, n = 28) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const k = 1 + wob * (Math.sin(a * 2 + seed) * 0.6 + Math.sin(a * 3 + seed * 1.7) * 0.4);
    pts.push([+(cx + Math.cos(a) * rx * k).toFixed(4), +(cy + Math.sin(a) * ry * k).toFixed(4)]);
  }
  return pts;
}
// 月牙形沙坑（圍在洞口前方）
function crescent(cx, cy, r0, r1, a0, a1, n = 18) {
  const out = [], inn = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n;
    const taper = Math.sin((i / n) * Math.PI);
    const ro = r0 + (r1 - r0) * (0.35 + 0.65 * taper);
    out.push([+(cx + Math.cos(a) * ro).toFixed(4), +(cy + Math.sin(a) * ro).toFixed(4)]);
    inn.push([+(cx + Math.cos(a) * r0).toFixed(4), +(cy + Math.sin(a) * r0).toFixed(4)]);
  }
  return out.concat(inn.reverse());
}

