// 平滑的有機外形（水池、沙坑）
function blob(cx, cy, rx, ry, seed = 1, wob = 0.12, n = 28) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const k = 1 + wob * (Math.sin(a * 2 + seed) * 0.6 + Math.sin(a * 3 + seed * 1.7) * 0.4);
    pts.push([+(cx + Math.cos(a) * rx * k).toFixed(4), +(cy + Math.sin(a) * ry * k).toFixed(4)]);
  }
  return pts;
}
// 月牙形沙坑（圍在洞口前方）
function crescent(cx, cy, r0, r1, a0, a1, n = 18) {
  const out = [], inn = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n;
    const taper = Math.sin((i / n) * Math.PI);
    const ro = r0 + (r1 - r0) * (0.35 + 0.65 * taper);
    out.push([+(cx + Math.cos(a) * ro).toFixed(4), +(cy + Math.sin(a) * ro).toFixed(4)]);
    inn.push([+(cx + Math.cos(a) * r0).toFixed(4), +(cy + Math.sin(a) * r0).toFixed(4)]);
  }
  return out.concat(inn.reverse());
}

const rect = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];
function circle(cx, cy, r, n = 32) {
  const pts = [];
  for (let i = 0; i < n; i++) { const a = (i / n) * Math.PI * 2; pts.push([+(cx + Math.cos(a) * r).toFixed(4), +(cy + Math.sin(a) * r).toFixed(4)]); }
  return pts;
}
// 沿中心線做出寬度 w 的球道，轉角以斜接延伸
function lane(line, w) {
  const L = [], R = [];
  const nrm = (x, y) => { const l = Math.hypot(x, y) || 1; return [x / l, y / l]; };
  for (let i = 0; i < line.length; i++) {
    const p = line[i], a = line[i - 1], b = line[i + 1];
    let d, k = 1;
    if (!a) d = nrm(b[0] - p[0], b[1] - p[1]);
    else if (!b) d = nrm(p[0] - a[0], p[1] - a[1]);
    else {
      const d1 = nrm(p[0] - a[0], p[1] - a[1]), d2 = nrm(b[0] - p[0], b[1] - p[1]);
      d = nrm(d1[0] + d2[0], d1[1] + d2[1]);
      k = 1 / Math.max(0.5, d[0] * d1[0] + d[1] * d1[1]);
    }
    const n = [-d[1], d[0]];
    L.push([+(p[0] + (n[0] * w * k) / 2).toFixed(4), +(p[1] + (n[1] * w * k) / 2).toFixed(4)]);
    R.push([+(p[0] - (n[0] * w * k) / 2).toFixed(4), +(p[1] - (n[1] * w * k) / 2).toFixed(4)]);
  }
  return L.concat(R.reverse());
}

